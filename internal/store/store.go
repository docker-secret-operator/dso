// Package store defines the persistence interface of the central secrets
// server. It knows nothing about SQL or encryption: values arrive and leave as
// opaque ciphertext. Types returned by listing methods carry metadata only and
// have no field that could hold a secret value.
package store

import (
	"context"
	"errors"
	"time"
)

var (
	ErrNotFound = errors.New("store: not found")
	// ErrConflict is returned when a uniqueness constraint is violated.
	ErrConflict = errors.New("store: already exists")
	// ErrVersionDisabled is returned when a disabled version is requested.
	ErrVersionDisabled = errors.New("store: version is disabled")
	// ErrLatestVersionDisabled is returned when the newest version of a secret
	// is disabled. There is deliberately NO fallback to an older version: that
	// version may be exactly the one being replaced after a compromise. Add a
	// new version, or ask for a specific version number.
	ErrLatestVersionDisabled = errors.New("store: the latest version is disabled; add a new version or request an explicit version")
	// ErrSchemaTooNew is returned when the database was written by a newer DSO.
	ErrSchemaTooNew = errors.New("store: database schema is newer than this binary supports")
	// ErrInvalid is returned for inputs the store refuses (e.g. empty ciphertext).
	ErrInvalid = errors.New("store: invalid input")
	// ErrTxActive is returned, without touching the database, when WithTx or a
	// standalone Store operation is called with the context that a WithTx
	// callback received (or one derived from it) while that transaction is still
	// open. It detects misuse of THAT context only: a call made with an unrelated
	// context, from another Store instance or from another process is an
	// independent caller and keeps its ordinary behaviour.
	ErrTxActive = errors.New("store: a transaction is already active on this context")
)

type Project struct {
	ID         string
	Slug       string
	Name       string
	WrappedDEK []byte // DEK encrypted by the root key; never the DEK itself
	DEKKeyID   string // id of the root key that wrapped the DEK
	DEKVersion int
	CreatedAt  time.Time
}

type Environment struct {
	ID        string
	ProjectID string
	Slug      string
	Name      string
	CreatedAt time.Time
}

// SecretMeta is a secret without any version payload.
type SecretMeta struct {
	ID                    string
	ProjectID             string
	EnvironmentID         string
	Name                  string
	CreatedAt             time.Time
	CreatedBy             string
	LatestVersion         int  // highest version number (enabled or not)
	LatestVersionDisabled bool // the latest version is disabled: reads of "latest" fail
	VersionCount          int
}

// VersionMeta is the metadata of one immutable version.
type VersionMeta struct {
	SecretID   string
	Version    int
	DEKVersion int
	CreatedAt  time.Time
	CreatedBy  string
	Comment    string
	DisabledAt *time.Time
	DisabledBy string
}

// VersionRecord is a version including its ciphertext, for the service layer
// only. It is never returned by listing methods.
type VersionRecord struct {
	VersionMeta
	Ciphertext []byte
	Nonce      []byte
}

// NewSecret creates a secret and its first (version 1) payload atomically.
// IDs are generated by the caller because the ciphertext is bound to them.
type NewSecret struct {
	ID            string
	ProjectID     string
	EnvironmentID string
	Name          string
	CreatedBy     string
	Comment       string
	DEKVersion    int
	Ciphertext    []byte
	Nonce         []byte
}

// SealFunc produces the payload of a new version once its number is known.
// It runs inside the write transaction so the number cannot change before the
// row is inserted; it must be fast and must not call the store.
type SealFunc func(version int) (ciphertext, nonce []byte, dekVersion int, err error)

// Operations is the set of 19 data and metadata operations. Store offers them as
// standalone calls (each with its own, unchanged, transactional behaviour); Tx
// offers the same set inside one transaction opened by Store.WithTx.
type Operations interface {
	CreateProject(ctx context.Context, p Project) error
	GetProjectBySlug(ctx context.Context, slug string) (Project, error)
	GetProject(ctx context.Context, id string) (Project, error)
	ListProjects(ctx context.Context) ([]Project, error)

	CreateEnvironment(ctx context.Context, e Environment) error
	GetEnvironmentBySlug(ctx context.Context, projectID, slug string) (Environment, error)
	ListEnvironments(ctx context.Context, projectID string) ([]Environment, error)

	// CreateSecret fails with ErrConflict if a non-deleted secret with the
	// same (environment, name) exists.
	CreateSecret(ctx context.Context, s NewSecret) error
	// GetSecret finds a non-deleted secret by name.
	GetSecret(ctx context.Context, environmentID, name string) (SecretMeta, error)
	ListSecrets(ctx context.Context, environmentID string) ([]SecretMeta, error)
	// DeleteSecret soft-deletes: versions are retained, the name is freed.
	DeleteSecret(ctx context.Context, secretID, actor string) error

	// AddVersion appends the next immutable version.
	AddVersion(ctx context.Context, secretID, actor, comment string, seal SealFunc) (version int, err error)
	// GetVersion returns an enabled version; ErrVersionDisabled otherwise.
	GetVersion(ctx context.Context, secretID string, version int) (VersionRecord, error)
	// GetLatestVersion returns the NEWEST version (highest number), or
	// ErrLatestVersionDisabled if that version is disabled. It never falls back
	// to an older enabled version.
	GetLatestVersion(ctx context.Context, secretID string) (VersionRecord, error)
	ListVersions(ctx context.Context, secretID string) ([]VersionMeta, error)
	// DisableVersion marks a version unreadable. Its ciphertext is retained
	// and unmodified. Disabling twice is a no-op.
	DisableVersion(ctx context.Context, secretID string, version int, actor string) error

	// GetMeta reads one database-level metadata value (ErrNotFound if absent).
	GetMeta(ctx context.Context, key string) ([]byte, error)
	// ListMeta returns every metadata row whose key starts with prefix, read in a
	// single statement (one consistent snapshot, unlike several GetMeta calls).
	ListMeta(ctx context.Context, prefix string) ([]MetaEntry, error)
	// PutMetaIfAbsent inserts ALL entries atomically, or none: it returns
	// (false, nil) without changing anything if any of the keys already exists.
	// Concurrent callers racing to initialise the same keys see exactly one winner.
	PutMetaIfAbsent(ctx context.Context, entries []MetaEntry) (inserted bool, err error)

	// AppendAuditEvent appends one event to the append-only, hash-chained audit
	// history (Phase 2 Step 5.3). The store fills in CreatedAt (if zero),
	// PrevHash and EventHash from the current chain tail; callers must not set
	// PrevHash/EventHash themselves. Called standalone it is a single-statement
	// autocommit append (consistent, but not atomic with anything else); called
	// as a Tx method inside Store.WithTx it commits or rolls back together with
	// whatever business mutation shares that transaction -- this is how the
	// approved design achieves atomicity for CreateProject, CreateEnvironment,
	// CreateSecret, AddVersion, DisableVersion and DeleteSecret without any
	// other interface change.
	AppendAuditEvent(ctx context.Context, ev AuditEvent) (AuditEvent, error)
	// ListAuditEvents returns every audit event in chain order (oldest first).
	// Intended for the verification routine and future read access; it is not
	// gated by any authorization today (see Step 5.2 §15 and the Step 5.3
	// design §8: deferred to the Step 5.2 matrix extension when Option B
	// exists).
	ListAuditEvents(ctx context.Context) ([]AuditEvent, error)
}

// Tx is the transaction-scoped view of the operations: every call runs inside the
// one IMMEDIATE transaction opened by Store.WithTx, so several of them commit or
// roll back together. A Tx is only valid inside the callback.
type Tx interface {
	Operations
}

type Store interface {
	Operations

	// WithTx runs fn in one IMMEDIATE transaction. It commits if fn returns nil
	// and rolls back if fn returns an error, the context is cancelled, or fn
	// panics (the panic is propagated, not swallowed). fn receives a derived
	// context marking the open transaction: nested WithTx and standalone
	// operations called with it (or a context derived from it) return
	// ErrTxActive immediately.
	WithTx(ctx context.Context, fn func(ctx context.Context, tx Tx) error) error

	SchemaVersion(ctx context.Context) (int, error)
	Close() error
}

// MetaEntry is one database-level metadata row.
type MetaEntry struct {
	Key   string
	Value []byte
}

// AuditEventType identifies the kind of security-relevant operation an audit
// event records. See docs/reviews/2026-10-25-central-store-phase2-audit-chain-design.md
// §4 for the approved event-coverage matrix this list implements.
type AuditEventType string

const (
	AuditInit                 AuditEventType = "init"
	AuditProjectCreate        AuditEventType = "project_create"
	AuditEnvironmentCreate    AuditEventType = "environment_create"
	AuditSecretCreate         AuditEventType = "secret_create"
	AuditSecretAddVersion     AuditEventType = "secret_add_version"
	AuditSecretGetReveal      AuditEventType = "secret_get_reveal"
	AuditSecretDisableVersion AuditEventType = "secret_disable_version"
	AuditSecretDelete         AuditEventType = "secret_delete"
)

// AuditOutcome is the result of the operation an audit event records.
type AuditOutcome string

const (
	AuditSuccess AuditOutcome = "success"
	AuditFailure AuditOutcome = "failure"
)

// AuditEvent is one row of the append-only, hash-chained audit history
// (approved design, Phase 2 Step 5.3). It must never carry a secret value,
// key material, or a raw error string -- ReasonCategory is a closed set of
// failure categories, not free text. ActorLabel is the existing
// caller-supplied created_by/disabled_by-style string: attribution only,
// never authenticated identity (see the approved Step 5.2 design and its
// addendum). PrevHash/EventHash are computed by the store at append time;
// callers must leave them zero.
type AuditEvent struct {
	ID              string
	SchemaVersion   int
	EventType       AuditEventType
	Outcome         AuditOutcome
	ReasonCategory  string // non-empty only on failure; closed category, never a raw error string
	ActorLabel      string // caller-supplied attribution only; never treated as authenticated identity
	ProjectSlug     string
	EnvironmentSlug string
	SecretName      string
	Version         int // 0 when not applicable to this event type
	CreatedAt       time.Time
	PrevHash        []byte // previous event's EventHash; nil for the first event
	EventHash       []byte // computed by the store; callers must not set this
}
