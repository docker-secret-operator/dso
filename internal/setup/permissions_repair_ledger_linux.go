//go:build linux

package setup

import (
	"errors"
	"fmt"
	"os"
	"syscall"

	"golang.org/x/sys/unix"

	"github.com/docker-secret-operator/dso/internal/bootstrap"
)

// The ledger key file format (internal/ledger/key.go, which this package must
// not import): "dso-ledger-key-v1\nk-<16 hex>\n<base64 of 32 bytes>\n". Only the
// size and the fixed public header line are examined here, to establish that a
// file is a ledger key before its mode is touched; the key id and the key bytes
// are never read, held or printed.
const (
	ledgerKeyHeader = "dso-ledger-key-v1\n"
	ledgerKeySize   = int64(len("dso-ledger-key-v1") + 1 + 18 + 1 + 44 + 1)
)

// inspectLedgerKey reports the ledger key. It never creates, regenerates,
// renames or removes it, and never reads past the header.
func (r *PermissionsRepairer) inspectLedgerKey() PermissionEntry {
	e, _ := r.examineLedgerKey(false)
	return e
}

// examineLedgerKey inspects the key through descriptors (the private directory
// is opened O_NOFOLLOW|O_DIRECTORY and the key is opened relative to it with
// O_NOFOLLOW). With fix=true and a verified key owned by root with a loose
// mode, the mode is tightened to 0400 on the open descriptor.
func (r *PermissionsRepairer) examineLedgerKey(fix bool) (PermissionEntry, error) {
	path := r.layout.LedgerDir + "/" + bootstrap.LedgerKeyFileName
	e := PermissionEntry{Path: path, Kind: "ledger key", Expected: "root 0400 (0600 accepted)"}
	manual := func(current, detail string) (PermissionEntry, error) {
		e.Status, e.Current, e.Detail = PermStatusManual, current, detail
		return e, nil
	}

	dir, err := os.OpenFile(r.layout.LedgerDir, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_DIRECTORY|syscall.O_CLOEXEC, 0) // #nosec G304 -- the fixed ledger directory; O_NOFOLLOW|O_DIRECTORY refuses a link and nothing is written
	if err != nil {
		switch {
		case os.IsNotExist(err):
			e.Status, e.Current = PermStatusAbsent, "absent"
			e.Detail = "the ledger directory does not exist yet; the agent creates it and the key on first start"
			return e, nil
		case errors.Is(err, syscall.ELOOP) || errors.Is(err, syscall.ENOTDIR):
			return manual("unsafe", "the ledger directory is a symbolic link or not a directory; the key was not inspected")
		default:
			return manual("unreadable", "cannot open the ledger directory: "+err.Error())
		}
	}
	defer func() { _ = dir.Close() }() // read-only descriptor
	dfd := int(dir.Fd())               // #nosec G115 -- an OS-provided small descriptor

	fd, err := syscall.Openat(dfd, bootstrap.LedgerKeyFileName, syscall.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK|syscall.O_CLOEXEC, 0)
	if err != nil {
		switch {
		case errors.Is(err, syscall.ENOENT):
			if r.keyEvidenceExists(dfd) {
				return manual("missing", "the ledger key is MISSING but ledger state exists beside it. It is never regenerated: "+
					"restore ledger.key from your backup of this host, or follow the recovery procedure in docs/RECOVERY_PROCEDURES.md. "+
					"Nothing was changed")
			}
			e.Status, e.Current = PermStatusAbsent, "absent"
			e.Detail = "no key yet (no ledger state either): it is generated by the agent on first start, never by this command"
			return e, nil
		case errors.Is(err, syscall.ELOOP):
			return manual("symbolic link", "the key path is a symbolic link: refused and untouched; establish who created it, do not follow it")
		default:
			return manual("unreadable", "cannot open the ledger key: "+err.Error())
		}
	}
	f := os.NewFile(uintptr(fd), "ledger.key") // #nosec G115 -- descriptor returned by openat
	defer func() { _ = f.Close() }()           // read-only descriptor

	fi, err := f.Stat()
	if err != nil {
		return manual("unreadable", "cannot stat the ledger key: "+err.Error())
	}
	st, ok := fi.Sys().(*syscall.Stat_t)
	if !ok {
		return manual("unknown owner", "ownership cannot be determined")
	}
	mode := fi.Mode() & permModeBits
	e.Current = fmt.Sprintf("%s %04o", ownerLabel(st.Uid, st.Gid), mode)
	switch {
	case !fi.Mode().IsRegular():
		return manual(e.Current, "the key path is not a regular file: untouched")
	case int(st.Uid) != r.ownerUID:
		return manual(e.Current, fmt.Sprintf("the key is owned by uid %d, not root: its ownership and contents cannot be established, so it is untouched. "+
			"If the key is unusable, restore it from backup (never regenerate: that would invalidate the ledger)", st.Uid))
	case st.Nlink != 1:
		return manual(e.Current, "the key has more than one hard link: untouched; find and remove the extra link by hand")
	case fi.Size() != ledgerKeySize:
		return manual(e.Current, "the file is not a valid ledger key (unexpected size): corrupt or not a key, untouched and never regenerated; restore from backup")
	}
	hdr := make([]byte, len(ledgerKeyHeader))
	if n, err := f.ReadAt(hdr, 0); err != nil || n != len(hdr) || string(hdr) != ledgerKeyHeader {
		return manual(e.Current, "the file does not carry the ledger key header: corrupt or not a key, untouched and never regenerated; restore from backup")
	}
	if mode == 0o400 || mode == 0o600 {
		e.Status = PermStatusOK
		return e, nil
	}
	e.Status = PermStatusChange
	e.Detail = fmt.Sprintf("mode %04o is too open for a key", mode)
	if !fix {
		e.fix = func() error {
			again, err := r.examineLedgerKey(true)
			if err == nil && again.Status != PermStatusChange {
				return fmt.Errorf("the key changed since inspection (now %s): not modified", again.Status)
			}
			return err
		}
		return e, nil
	}
	if err := r.chmodKey(f, 0o400); err != nil {
		return e, fmt.Errorf("chmod ledger key: %w", err)
	}
	return e, nil
}

// keyEvidenceExists reports whether ledger state (the ledger file, the key-id
// marker or a preserved key) exists beside a missing key, which makes the
// absence a LOST key rather than a first run.
func (r *PermissionsRepairer) keyEvidenceExists(dfd int) bool {
	for _, name := range []string{"ledger.json", "ledger.key.id"} {
		var st unix.Stat_t
		if err := unix.Fstatat(dfd, name, &st, unix.AT_SYMLINK_NOFOLLOW); err == nil {
			return true
		}
	}
	return false
}
